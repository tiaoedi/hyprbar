local root = arg[1] or "."
local m = dofile(root .. "/scheduler.luau")
local function test(name, f) f(); print("PASS " .. name) end

test("usage counts elapsed time only once and pauses with reminders", function()
  local s = m.new({}, 0, "2026-10-31")
  m.tick(s, 1000, s.day)
  local v = m.view(s, s.last)
  assert(v.usageMs == 1000 and v.sessionMs == 1000, "missing daily/session usage counters")
  m.tick(s, 1000, s.day)
  assert(m.view(s, s.last).usageMs == 1000, "duplicate tick counted twice")
  m.command(s, "pause", s.last)
  m.tick(s, 6000, s.day)
  assert(m.view(s, s.last).usageMs == 1000, "paused time was counted")
  m.command(s, "resume", s.last)
  m.tick(s, 8000, s.day)
  assert(m.view(s, s.last).sessionMs == 3000, "resume did not continue session")
end)

test("usage persists daily total not session and rolls over without prior-day carry", function()
  local s = m.new({}, 0, "2026-10-31", {day="2026-10-31", count=3, usageMs=7200000})
  assert(s.usageMs == 7200000 and s.sessionMs == 0, "daily usage was not restored")
  m.tick(s, 1000, s.day)
  local saved = m.persist(s)
  assert(saved.usageMs == 7201000 and saved.sessionMs == nil)
  m.tick(s, 2000, "2026-11-01")
  assert(s.usageMs == 0 and s.sessionMs == 2000 and s.count == 0, "daily rollover leaked yesterday")
  assert(m.new({}, 0, "2026-11-02", saved).usageMs == 0)
  assert(m.new({}, 0, "2026-10-31", {day="2026-10-31",usageMs="bad"}).usageMs == 0)
  assert(m.new({}, 0, "2026-10-31", {day="2026-10-31",usageMs=math.huge}).usageMs == 0)
  assert(m.new({}, 0, "2026-10-31", {day="2026-10-31",usageMs=999999999}).usageMs == 86400000)
end)

test("usage excludes suspension and backwards jumps but resumes after them", function()
  local s = m.new({}, 1000, "2026-10-31")
  m.tick(s, 2000, s.day)
  m.tick(s, 7200000, s.day)
  assert(s.usageMs == 1000 and s.sessionMs == 1000)
  m.tick(s, 1, s.day)
  assert(s.usageMs == 1000 and s.sessionMs == 1000)
  m.tick(s, 1001, s.day)
  assert(s.usageMs == 2000 and s.sessionMs == 2000)
end)
