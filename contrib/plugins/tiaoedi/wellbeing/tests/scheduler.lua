local root = arg[1] or "."
local function test(name, fn)
  fn()
  print("PASS " .. name)
end
local function model() return dofile(root .. "/scheduler.luau") end
local function advance(m, s, target, day)
  local alerts = {}
  while s.last < target do
    local batch = m.tick(s, math.min(target, s.last + 1000), day or "2026-10-31")
    for _, id in ipairs(batch) do alerts[#alerts + 1] = id end
  end
  return alerts
end
test("defaults and exact eye-rest boundary", function()
  local m = model()
  local s = m.new({}, 0, "2026-10-31")
  assert(s.reminders.water.interval == 2700000)
  assert(s.reminders.eyes.interval == 1200000)
  assert(s.reminders.stretch.interval == 3600000)
  assert(#advance(m, s, 1199999) == 0)
  local a = advance(m, s, 1200000)
  assert(#a == 1 and a[1] == "eyes")
end)
test("pending suppresses duplicates until completion", function()
  local m = model(); local s = m.new({}, 0, "2026-10-31")
  advance(m, s, 1200000)
  assert(#advance(m, s, 1201000) == 0, "pending reminder repeated")
  assert(s.reminders.eyes.pending)
  assert(m.command(s, "eyes", 1201000))
  assert(not s.reminders.eyes.pending and s.reminders.eyes.due == 2401000)
  m.command(s, "water", 1201000)
  assert(s.count == 1 and s.reminders.water.due == 3901000)
  assert(not m.command(s, "unknown", 1201000))
end)
test("pause freezes clocks and snooze rearms for five minutes", function()
  local m = model(); local s = m.new({}, 0, "2026-10-31")
  advance(m, s, 1000); m.command(s, "pause", 1000)
  assert(s.paused)
  assert(#advance(m, s, 1500000) == 0)
  m.command(s, "resume", 1500000)
  assert(not s.paused and s.reminders.eyes.due == 2699000)
  m.command(s, "snooze", 1500000)
  assert(#advance(m, s, 1799999) == 0)
  assert(#advance(m, s, 1800000) == 3)
  m.command(s, "pause", 1800000)
  m.command(s, "snooze", 1800000)
  m.command(s, "water", 1800000)
  advance(m, s, 1900000)
  m.command(s, "resume", 1900000)
  assert(s.reminders.eyes.due == 2200000 and not s.reminders.eyes.pending)
  assert(s.reminders.water.due == 4600000)
end)
test("large forward or backward jump resets timers without burst", function()
  local m = model(); local s = m.new({}, 0, "2026-10-31")
  assert(#m.tick(s, 7200000, s.day) == 0)
  assert(s.reminders.eyes.due == 8400000)
  advance(m, s, 8400000)
  assert(s.reminders.eyes.pending)
  assert(#m.tick(s, 1, s.day) == 0)
  assert(not s.reminders.eyes.pending and s.reminders.eyes.due == 1200001)
end)
test("daily rollover and bounded persistence restoration", function()
  local m = model(); local s = m.new({}, 0, "2026-10-31", { day = "2026-10-31", count = 99999, paused = true })
  assert(s.count == 999 and s.paused)
  m.tick(s, 1000, "2026-11-01")
  assert(s.count == 0 and s.day == "2026-11-01")
  m.command(s, "water", 1000)
  local p = m.persist(s)
  assert(p.count == 1 and p.day == s.day and p.paused and p.reminders == nil)
  assert(m.new({}, 0, "2026-11-02", p).count == 0)
  assert(m.new({}, 0, "2026-11-01", "bad").count == 0)
end)
test("settings clamp reject invalid numbers and reconfigure only changed timers", function()
  local m = model(); local s = m.new({ water_minutes = -5, eyes_minutes = 9999, stretch_minutes = "bad", water_enabled = false }, 0, "2026-10-31")
  assert(s.reminders.water.interval == 60000 and not s.reminders.water.enabled)
  assert(s.reminders.eyes.interval == 1440 * 60000)
  assert(s.reminders.stretch.interval == 3600000)
  m.configure(s, { water_minutes = 0/0, eyes_minutes = math.huge, stretch_minutes = 2.9 }, 1000)
  assert(s.reminders.water.interval == 2700000 and s.reminders.water.enabled)
  assert(s.reminders.eyes.interval == 1200000)
  assert(s.reminders.stretch.interval == 120000)
  local due = s.reminders.eyes.due
  m.configure(s, { stretch_minutes = 2 }, 2000)
  assert(s.reminders.eyes.due == due)
  local v = m.view(s, 3000)
  assert(v.reminders.stretch.remainingMs == 118000 and v.day == s.day)
  v.reminders.eyes.pending = true
  assert(not s.reminders.eyes.pending, "view must be detached")
end)
