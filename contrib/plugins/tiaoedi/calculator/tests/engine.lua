local root = arg[1] or "."
local ok, calc = pcall(dofile, root .. "/engine.luau")
assert(ok and type(calc)=="table", "motor da calculadora ainda não implementado")
local function test(name, f) f(); print("PASS " .. name) end
local function equal(text, expected)
  local value, err = calc.evaluate(text)
  assert(value == expected, text .. ": " .. tostring(value) .. " / " .. tostring(err))
end
test("arithmetic respects precedence parentheses and decimals", function()
  equal("2+3*4", 14)
  equal("(2+3)*4", 20)
  equal("10 / 4", 2.5)
  equal("1,5 + .5", 2)
  equal("-2 + +3", 1)
end)
test("power percent square root answer and scientific notation", function()
  equal("2^3^2", 512)
  equal("-2^2", -4)
  equal("2^-2", 0.25)
  equal("25% * 200", 50)
  equal("200+10%", 220)
  equal("sqrt(81)", 9)
  equal("1e3 + 2.5e-1", 1000.25)
  equal("6 × 7 − 2 ÷ 2", 41)
  assert(calc.evaluate("ans+2", 40) == 42)
  assert(calc.evaluate("pi") == math.pi)
end)
test("invalid unsafe and non-finite expressions return errors", function()
  for _, text in ipairs({"", "1/0", "0/0", "sqrt(-1)", "(-1)^.5", "1e999", "9^999", "1+", "(1+2", "1 2", "os.execute('id')", "1;2", "2**3", string.rep("(",40).."1"..string.rep(")",40), string.rep("1",513)}) do
    local value, err = calc.evaluate(text)
    assert(value == nil and type(err)=="string" and #err>0, "not rejected: " .. text)
  end
  assert(calc.evaluate("ans", math.huge) == nil)
  assert(calc.evaluate({}) == nil)
end)
